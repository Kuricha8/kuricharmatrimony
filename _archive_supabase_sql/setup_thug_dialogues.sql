-- 1. Create the thug_dialogues table
CREATE TABLE IF NOT EXISTS public.thug_dialogues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dialogue_text TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('MATCH', 'NO_MATCH')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Enable RLS and add basic policies
ALTER TABLE public.thug_dialogues ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read for thug_dialogues"
    ON public.thug_dialogues FOR SELECT
    USING (true);

CREATE POLICY "Allow all modifications for thug_dialogues"
    ON public.thug_dialogues FOR ALL
    USING (true);

-- 3. Create RPC function for random fetching
CREATE OR REPLACE FUNCTION get_random_thug_dialogue(p_category text)
RETURNS text AS $$
DECLARE
    result text;
BEGIN
    SELECT dialogue_text INTO result
    FROM public.thug_dialogues
    WHERE category = p_category
    ORDER BY random()
    LIMIT 1;
    
    RETURN result;
END;
$$ LANGUAGE plpgsql;
