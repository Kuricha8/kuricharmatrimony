-- ============================================================================
-- MIGRATION SCRIPT: Create 'tharavadu' Table & Seed All 57 Lineage Clans
-- Table: tharavadu
-- Columns: id, name, gothram, description, created_at
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.tharavadu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    gothram TEXT NOT NULL CHECK (gothram IN ('PANTHI', 'BANDHU')),
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Comments on table & columns
COMMENT ON TABLE public.tharavadu IS 'Kurichiyar traditional tharavadu clans and lineage records';
COMMENT ON COLUMN public.tharavadu.name IS 'Traditional tharavadu / house name';
COMMENT ON COLUMN public.tharavadu.gothram IS 'Moiety / Clan category: PANTHI or BANDHU';
COMMENT ON COLUMN public.tharavadu.description IS 'Optional location, branch or ancestral notes';

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_tharavadu_name ON public.tharavadu (name);
CREATE INDEX IF NOT EXISTS idx_tharavadu_gothram ON public.tharavadu (gothram);
CREATE INDEX IF NOT EXISTS idx_tharavadu_created_at ON public.tharavadu (created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.tharavadu ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any
DROP POLICY IF EXISTS "Allow public read access on tharavadu" ON public.tharavadu;
DROP POLICY IF EXISTS "Allow authenticated admin full access on tharavadu" ON public.tharavadu;

-- Allow everyone (anonymous + authenticated) to read Tharavadu list
CREATE POLICY "Allow public read access on tharavadu"
ON public.tharavadu FOR SELECT
TO anon, authenticated
USING (true);

-- Allow authenticated users / admins to insert, update, or delete Tharavadu
CREATE POLICY "Allow authenticated admin full access on tharavadu"
ON public.tharavadu FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

-- Enable Realtime publication so mobile & web apps receive live updates
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
        AND schemaname = 'public'
        AND tablename = 'tharavadu'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.tharavadu;
    END IF;
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

